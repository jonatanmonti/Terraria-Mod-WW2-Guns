def text(img, x, y, s, color, scale=1, shadow=None, spacing=1):
    from PIL import ImageDraw
    d = ImageDraw.Draw(img)
    for pass_ in ([shadow, color] if shadow else [color]):
        off = max(1, scale//3) if pass_ is shadow and shadow else 0
        cx = x
        for ch in s.upper():
            g = F.get(ch, F[' '])
            for r, row in enumerate(g):
                for c, b in enumerate(row):
                    if b == '1':
                        d.rectangle([cx+c*scale+off, y+r*scale+off, cx+(c+1)*scale-1+off, y+(r+1)*scale-1+off], fill=pass_)
            cx += (5+spacing)*scale
    return cx
def width(s, scale=1, spacing=1): return len(s)*(5+spacing)*scale - spacing*scale
